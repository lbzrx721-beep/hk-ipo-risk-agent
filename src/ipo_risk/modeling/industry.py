def normalize_industry(value: object) -> NormalizedIndustry:
    """把原始行业描述映射为稳定的两级行业。"""
    raw = None if value is None else str(value).strip()
    if not raw or raw.lower() in {"nan", "none", "null"}:
        return NormalizedIndustry(raw=None, level_1="综合及其他", level_2="未分类")
    normalized = unicodedata.normalize("NFKC", raw).lower()
    normalized = re.sub(r"[\s/、()（）·_-]+", " ", normalized)
    padded = f" {normalized} "
    for level_1, level_2, keywords in _RULES:
        if any(keyword.lower() in padded for keyword in keywords):
            return NormalizedIndustry(raw=raw, level_1=level_1, level_2=level_2)
    return NormalizedIndustry(raw=raw, level_1="综合及其他", level_2="其他")


